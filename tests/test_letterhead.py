"""The PDF letterhead follows the ACTIVE company: every PDF path, after a company switch, blank fields, deleted companies, jobs."""
import io
import json

from django.core.files.base import ContentFile
from django.test import override_settings
from django.urls import reverse

from core.models import ExportJob
from core.reports import letterhead
from core.reports.letterhead import letterhead_for
from core.reports.resources.export import run_job
from core.files.storage import private_storage

from tests.dummyapp.models import Garment

from .base import CoreTestCase, make_user
from .test_custom_reports import pdf_text

PERMS = ["dummyapp.view_garment", "dummyapp.add_garment", "dummyapp.change_garment", "dummyapp.view_fabric",
         "dummyapp.view_garmentline"]


def png(width, height, colour):
    from PIL import Image

    buffer = io.BytesIO()
    Image.new("RGB", (width, height), colour).save(buffer, "PNG")
    return buffer.getvalue()


class LetterheadCompanyTests(CoreTestCase):
    def setUp(self):
        super().setUp()
        self.logo_a, self.logo_b = png(40, 20, "red"), png(30, 30, "blue")
        for company, name, address, mail, logo in ((self.company_a, "Alpha Knit Ltd", "1 Alpha Road", "a@alpha.example", self.logo_a),
                                                   (self.company_b, "Beta Garments Ltd", "2 Beta Street", "b@beta.example", self.logo_b)):
            company.name, company.address, company.email, company.website = name, address, mail, f"https://{name[:4].lower()}.example"
            company.factory_address, company.phone = f"Factory of {name}", "+880 1"
            company.logo.save(f"{name[:4]}.png", ContentFile(logo), save=False)
            company.save()
        self.user = make_user("both@example.com", self.company_a, perms=PERMS)
        self.user.profile.companies.add(self.company_b)
        Garment.objects.create(company=self.company_a, name="Tee A", style_no="A-1", price=1)
        Garment.objects.create(company=self.company_b, name="Tee B", style_no="B-1", price=2)

    def switch(self, client, company):
        r = client.post(reverse("core:switch_company"), {"company": company.pk})
        self.assertEqual(r.status_code, 302)

    def assert_only(self, data, mine, other):
        self.assertTrue(data.startswith(b"%PDF"))
        text = pdf_text(data)
        for expected in (mine.name, mine.address, mine.factory_address, mine.email, f"This report is generated by {mine.name}"):
            self.assertIn(expected, text)
        for absent in (other.name, other.address, other.email):
            self.assertNotIn(absent, text)

    # ---------------------------------------------------------------------------------------------------- the data layer
    def test_each_company_supplies_its_own_details(self):
        for company, logo in ((self.company_a, self.logo_a), (self.company_b, self.logo_b)):
            head = letterhead_for(company.pk)
            self.assertEqual(head.name, company.name)
            self.assertEqual(head.address_lines, (company.address, company.factory_address))
            self.assertEqual((head.email, head.phone, head.website), (company.email, company.phone, company.website))
            self.assertEqual(head.logo, logo)
            self.assertEqual(head.brand, company.name)
            self.assertIsNotNone(head.logo_reader())

    def test_defaults_carry_no_company_details(self):
        defaults = letterhead.DEFAULT_LETTERHEAD
        self.assertTrue(defaults["from_company"])
        for key in ("name", "email", "website", "phone", "logo"):
            self.assertFalse(defaults[key], key)
        self.assertFalse(defaults["address_lines"])
        self.assertIsNone(defaults["brand"])                     # = the company's name
        head = letterhead_for(None)
        self.assertEqual((head.name, head.address_lines, head.email, head.website, head.phone, head.logo, head.brand),
                         ("", (), "", "", "", None, ""))
        self.assertNotIn("ocms", repr(defaults).lower())

    @override_settings(CORE_PDF_LETTERHEAD={"name": "Fallback Group", "address_lines": ["9 Fallback Way"], "email": "f@fb.example",
                                            "website": "https://fb.example", "phone": "123", "brand": "OurERP"})
    def test_blank_company_fields_fall_back_to_the_setting_then_to_empty(self):
        self.company_a.factory_address = self.company_a.email = self.company_a.website = self.company_a.phone = ""
        self.company_a.logo = None
        self.company_a.save()
        head = letterhead_for(self.company_a.pk)
        self.assertEqual(head.name, "Alpha Knit Ltd")                        # the company wins where it is filled in
        self.assertEqual(head.address_lines, ("1 Alpha Road",))
        self.assertEqual((head.email, head.website, head.phone), ("f@fb.example", "https://fb.example", "123"))
        self.assertIsNone(head.logo)                                         # no logo anywhere -> none
        self.assertEqual(head.brand, "OurERP")
        with override_settings(CORE_PDF_LETTERHEAD={}):
            head = letterhead_for(self.company_a.pk)
            self.assertEqual((head.email, head.website, head.phone, head.brand), ("", "", "", "Alpha Knit Ltd"))

    @override_settings(CORE_PDF_LETTERHEAD={"from_company": False, "name": "Site Name"})
    def test_from_company_false_ignores_the_company(self):
        head = letterhead_for(self.company_a.pk)
        self.assertEqual((head.name, head.address_lines, head.logo, head.brand), ("Site Name", (), None, "Site Name"))

    def test_missing_or_deleted_company_is_safe(self):
        pk = self.company_b.pk
        self.company_b.delete()                                              # soft delete
        head = letterhead_for(pk)
        self.assertEqual((head.name, head.address_lines), ("", ()))
        self.assertEqual(letterhead_for(999999).name, "")
        self.assertEqual(letterhead_for("junk").name, "")
        with override_settings(CORE_PDF_LETTERHEAD={"name": "Fallback"}):
            self.assertEqual(letterhead_for(pk).name, "Fallback")

    def test_company_edit_shows_in_the_next_pdf(self):                       # nothing cached
        self.assertEqual(letterhead_for(self.company_a.pk).name, "Alpha Knit Ltd")
        self.company_a.name = "Alpha Renamed"
        self.company_a.save()
        self.assertEqual(letterhead_for(self.company_a.pk).name, "Alpha Renamed")

    # ------------------------------------------------------------------------------------------- every PDF path, switching
    def test_list_export_follows_the_switch(self):
        client = self.login(self.user)
        url = reverse("core:resource_export", args=["garments", "pdf"])
        self.assert_only(client.get(url).content, self.company_a, self.company_b)
        self.switch(client, self.company_b)
        self.assert_only(client.get(url).content, self.company_b, self.company_a)
        self.switch(client, self.company_a)
        self.assert_only(client.get(url).content, self.company_a, self.company_b)

    def test_report_builder_and_query_builder_follow_the_switch(self):
        client = self.login(self.user)
        report = reverse("core:report_builder", args=["garments"])
        query = reverse("core:query_builder", args=["dummyapp.garment"])
        report_post = {"action": "export", "format": "pdf", "definition": '{"columns": ["name", "price"]}'}
        query_post = {"action": "export", "format": "pdf", "definition": json.dumps({"columns": [{"path": "name"}]})}
        for active, other in ((self.company_a, self.company_b), (self.company_b, self.company_a)):
            self.switch(client, active)
            self.assert_only(client.post(report, report_post).content, active, other)
            self.assert_only(client.post(query, query_post).content, active, other)

    def test_multi_company_report_scope_keeps_the_active_company_header(self):
        profile = self.user.profile
        profile.report_all_companies = True
        profile.save()
        client = self.login(self.user)
        self.switch(client, self.company_b)
        r = client.post(reverse("core:report_builder", args=["garments"]),
                        {"action": "export", "format": "pdf", "definition": '{"columns": ["name"]}', "company_scope": "all"})
        text = pdf_text(r.content)
        self.assertIn("Tee A", text)                                          # data from both companies ...
        self.assertIn("Tee B", text)
        self.assert_only(r.content, self.company_b, self.company_a)          # ... header of the active one only

    def test_custom_report_follows_the_switch(self):
        client = self.login(self.user)
        url = reverse("core:custom_report", args=["garment-sheet"])
        self.assert_only(client.get(url, {"style_no": "A-1", "format": "pdf"}).content, self.company_a, self.company_b)
        self.switch(client, self.company_b)
        self.assert_only(client.get(url, {"style_no": "B-1", "format": "pdf"}).content, self.company_b, self.company_a)

    def test_record_pdf_uses_the_active_company(self):
        client = self.login(self.user)
        self.switch(client, self.company_b)
        tee = Garment.objects.get(style_no="B-1")
        r = client.get(reverse("core:resource_record_export", args=["garments", tee.pk, "pdf"]))
        self.assertEqual(r.status_code, 200)
        self.assert_only(r.content, self.company_b, self.company_a)

    def test_page_header_and_switcher_update_at_once(self):
        client = self.login(self.user)
        html = client.get(reverse("core:dashboard")).content.decode()
        self.assertIn('<span class="core-company-name text-truncate">Alpha Knit Ltd</span>', html)
        self.switch(client, self.company_b)
        html = client.get(reverse("core:dashboard")).content.decode()
        self.assertIn('<span class="core-company-name text-truncate">Beta Garments Ltd</span>', html)
        self.assertNotIn('<span class="core-company-name text-truncate">Alpha Knit Ltd</span>', html)

    def test_background_export_uses_the_jobs_company(self):
        self.assertEqual(self.user.profile.active_company_id, self.company_a.pk)     # the owner works in A now ...
        job = ExportJob.objects.create(owner=self.user, company=self.company_b, target_type="resource", target_key="garments",
                                       export_format="pdf", params={})
        run_job(job.pk)                                                             # ... the job was started in B
        job.refresh_from_db()
        self.assertEqual(job.status, ExportJob.DONE, job.error)
        with private_storage.open(job.file_name, "rb") as handle:
            data = handle.read()
        self.assert_only(data, self.company_b, self.company_a)
        self.assertIn("Tee B", pdf_text(data))
        self.assertNotIn("Tee A", pdf_text(data))
