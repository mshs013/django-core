class CustomReportTests(CoreTestCase):
    def setUp(self):
        super().setUp()
        self.user = make_user("cr@example.com", self.company_a, perms=PERMS)
        self.garment = Garment.objects.create(company=self.company_a, name="Polo", style_no="P-1", price=12)
        for n, qty in ((1, 5), (2, 7)):
            GarmentLine.objects.create(garment=self.garment, description=f"line {n}", qty=qty, position=n)
        Garment.objects.create(company=self.company_b, name="Foreign", style_no="F-1", price=1)
        self.url = reverse("core:custom_report", args=["garment-sheet"])

    def test_listed_and_previewed(self):
        client = self.login(self.user)
        self.assertContains(client.get(reverse("core:report_list")), "Garment sheet")
        r = client.get(self.url, {"style_no": "P-1", "run": "1"})
        self.assertContains(r, "Garment Sheet - P-1")
        self.assertContains(r, "line 2")
        self.assertContains(r, "<td class=\"text-end\">12</td>", html=False)       # total row

    def test_form_errors_do_not_run(self):
        r = self.login(self.user).get(self.url, {"run": "1"})
        self.assertEqual(r.status_code, 200)
        self.assertNotIn("output", r.context)

    def test_permission_is_enforced(self):
        nobody = make_user("np@example.com", self.company_a)
        self.assertEqual(self.login(nobody).get(self.url).status_code, 403)
        self.assertNotContains(self.login(nobody).get(reverse("core:report_list")), "Garment sheet")

    def test_run_scopes_to_the_active_company(self):
        r = self.login(self.user).get(self.url, {"style_no": "F-1", "run": "1"})
        self.assertContains(r, "No garment with that style no.")

    def test_pdf_and_csv_downloads(self):
        approvals.submit_for_approval(self.user, self.garment)            # signatures come from the approval history
        client = self.login(self.user)
        pdf = client.get(self.url, {"style_no": "P-1", "format": "pdf"})
        self.assertEqual(pdf["Content-Type"], "application/pdf")
        text = pdf_text(pdf.content)
        for expected in ("Garment Sheet - P-1", "Quote the style no.", "Prepared By", "Checked By", "Approved By", "Page 1 of 1"):
            self.assertIn(expected, text)
        data = client.get(self.url, {"style_no": "P-1", "format": "csv"}).content.decode("utf-8-sig")
        rows = list(csv.reader(io.StringIO(data)))
        self.assertEqual(rows[0], ["#", "Description", "Qty"])
        self.assertEqual(rows[-1], ["Total", "", "12"])
        self.assertEqual(client.get(self.url, {"style_no": "P-1", "format": "exe"}).status_code, 404)

    def test_mail_this_report_example_from_the_docs(self):            # docs/MAIL.md section 4.3
        from django.core.files.base import ContentFile

        from core.crud.access import Ctx
        from core.mail.service import send
        from core.models import Mailbox
        from core.reports.custom import custom_report_bytes, execute

        colleague = make_user("colleague@example.com", self.company_a)
        ctx = Ctx(user=self.user, company_ids=frozenset({self.company_a.pk}), company_id=self.company_a.pk,
                  member_ids=frozenset({self.company_a.pk}))
        report = get_custom_report("garment-sheet")
        output = execute(report, ctx, {"style_no": "P-1"})
        data, name, _ = custom_report_bytes(report, output, ctx, "pdf")
        message = send(self.user, to=[colleague.pk], subject=output.title, body="Attached.", files=[ContentFile(data, name=name)])
        self.assertEqual(message.attachments.count(), 1)
        self.assertTrue(Mailbox.objects.filter(owner=colleague, message=message).exists())

    def test_registration_is_validated(self):
        with self.assertRaises(ImproperlyConfigured):
            register_custom_report("garment-sheet", "dup", lambda c, p: None, permission=())
        with self.assertRaises(ImproperlyConfigured):
            register_custom_report("Bad Key", "x", lambda c, p: None, permission=())
        with self.assertRaises(TypeError):
            register_custom_report("no-perm", "x", lambda c, p: None)                     # permission is required (fail closed)

    def test_run_must_return_a_report_output(self):
        register_custom_report("broken", "Broken", lambda ctx, params: [], permission=())
        try:
            with self.assertRaises(ImproperlyConfigured):
                self.login(self.user).get(reverse("core:custom_report", args=["broken"]), {"run": "1"})
        finally:
            unregister_custom_report("broken")

    def test_report_without_form_runs_directly(self):
        register_custom_report("count", "Count", lambda ctx, params: ReportOutput([("n", "N")], [{"n": 1}]), permission=())
        try:
            self.assertContains(self.login(self.user).get(reverse("core:custom_report", args=["count"])), "<td>1</td>", html=False)
        finally:
            unregister_custom_report("count")
        self.assertIsNone(get_custom_report("count"))

    def test_own_date_formats_win_on_screen_and_in_pdf(self):
        run = lambda ctx, params: ReportOutput([("d", "Day")], [{"d": dt.date(2026, 10, 21)}])  # noqa: E731
        register_custom_report("dated", "Dated", run, permission=(), date_formats={"date": "d/m/Y"})
        register_custom_report("dated-site", "Dated site", run, permission=())
        try:
            client = self.login(self.user)
            self.assertContains(client.get(reverse("core:custom_report", args=["dated"])), "<td>21/10/2026</td>", html=False)
            self.assertIn("21/10/2026", pdf_text(client.get(reverse("core:custom_report", args=["dated"]), {"format": "pdf"}).content))
            self.assertIn("21-Oct-2026", pdf_text(client.get(reverse("core:custom_report", args=["dated-site"]), {"format": "pdf"}).content))
        finally:
            unregister_custom_report("dated")
            unregister_custom_report("dated-site")

    def test_list_pdf_uses_the_resource_date_formats(self):
        from core.crud.registry import get_resource

        Garment.objects.filter(pk=self.garment.pk).update(ordered_on=dt.date(2026, 10, 21))
        cfg = get_resource("garments")
        old = cfg.list_fields, cfg.date_formats
        cfg.list_fields, cfg.date_formats = ("name", "ordered_on"), {"date": "Y/m/d"}
        try:
            r = self.login(self.user).get(reverse("core:resource_export", args=["garments", "pdf"]))
            self.assertIn("2026/10/21", pdf_text(r.content))
        finally:
            cfg.list_fields, cfg.date_formats = old


class ApprovalSignatureTests(CoreTestCase):
    def test_boxes_follow_the_approval_history(self):
        submitter = make_user("sub@example.com", self.company_a, perms=PERMS)
        merch = make_user("merch@example.com", self.company_a, perms=PERMS)
        garment = Garment.objects.create(company=self.company_a, name="Tee", style_no="T", price=3)
        self.assertEqual(approval_signatures(garment), [])
        req = approvals.submit_for_approval(submitter, garment)
        approvals.submit_approval_step(merch, req.pk, "approve")
        sigs = approval_signatures(garment, labels={"merch": "Checked By", "manager": "Approved By"})
        self.assertEqual([s.label for s in sigs], ["Prepared By", "Checked By", "Approved By"])
        self.assertEqual((sigs[0].name, sigs[1].name, sigs[2].name), ("sub@example.com", "merch@example.com", ""))
        self.assertIsNotNone(sigs[1].when)
        self.assertEqual(len(approval_signatures(garment, include_pending=False)), 2)
