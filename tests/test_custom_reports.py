def pdf_text(data: bytes) -> str:
    """Text drawn in a reportlab PDF (decodes the ASCII85 + Flate content streams; good enough for assertions)."""
    out = []
    for raw in re.findall(rb"\bstream\r?\n(.*?)endstream", data, re.S):
        raw = raw.strip()
        try:
            if raw.endswith(b"~>"):
                raw = base64.a85decode(raw[:-2])
            out.append(zlib.decompress(raw).decode("latin-1"))
        except (ValueError, zlib.error):
            out.append(raw.decode("latin-1", "ignore"))
    return "\n".join(out)


class LetterheadTests(CoreTestCase):
    def _pdf(self, rows=2, **meta):
        meta = {"generated_by": "Report User", "generated_at": dt.datetime(2026, 10, 11, 13, 47, 58), **meta}
        return render_pdf("Yarn Work Order No - 17", ["A", "B"], [[i, "x"] for i in range(rows)], meta)

    def test_header_and_footer_use_the_active_company(self):
        self.company_a.email, self.company_a.website = "info@a.example", "http://a.example"
        self.company_a.save()
        text = pdf_text(self._pdf(company_id=self.company_a.pk))
        for expected in ("Company A", "Test address", "info@a.example", "http://a.example",
                         "Yarn Work Order No - 17", "Generated On 11-Oct-2026 01:47:58 PM", "Generated By: Report User",
                         "Page 1 of 1", "This report is generated by Company A"):
            self.assertIn(expected, text)

    def test_page_x_of_y_on_every_page(self):
        text = pdf_text(self._pdf(rows=150))
        total = int(re.search(r"Page 1 of (\d+)", text).group(1))
        self.assertGreater(total, 1)
        for n in range(1, total + 1):
            self.assertIn(f"Page {n} of {total}", text)

    def test_signatures_are_printed(self):
        sigs = [Signature("Prepared By", "Ann", dt.datetime(2026, 9, 15, 12, 10, 33)), Signature("Approved By")]
        text = pdf_text(self._pdf(signatures=sigs))
        self.assertIn("Prepared By", text)
        self.assertIn("15-Sep-2026 12:10:33 PM", text)
        self.assertIn("Approved By", text)

    @override_settings(CORE_PDF_LETTERHEAD={"name": "Acme Knit", "address_lines": ["1 Mill Road"], "email": "", "website": "",
                                            "logo": "", "brand": "AcmeERP"})
    def test_letterhead_is_configurable(self):
        text = pdf_text(self._pdf())
        self.assertIn("Acme Knit", text)
        self.assertIn("1 Mill Road", text)
        self.assertIn("This report is generated by AcmeERP", text)
        self.assertNotIn("ocmsbd", text)

    def test_letterhead_from_the_active_company(self):
        self.company_a.address, self.company_a.email = "9 Factory Lane", "hello@a.example"
        self.company_a.save()
        head = letterhead_for(self.company_a.pk)
        self.assertEqual(head.name, self.company_a.name)
        self.assertEqual(head.address_lines[0], "9 Factory Lane")
        self.assertEqual(head.email, "hello@a.example")
        self.assertEqual(head.website, letterhead.DEFAULT_LETTERHEAD["website"])     # blank on the company -> default ("") kept

    @override_settings(CORE_PDF_LETTERHEAD_CLASS="tests.test_custom_reports.PlainLetterhead")
    def test_layout_class_is_replaceable(self):
        text = pdf_text(self._pdf())
        self.assertIn("PLAIN HEADER", text)
        self.assertNotIn("Page 1 of 1", text)

    def test_broken_logo_never_breaks_the_pdf(self):
        data = self._pdf(letterhead=Letterhead(name="X", logo=b"not an image"))
        self.assertTrue(data.startswith(b"%PDF"))

    def test_list_export_pdf_carries_the_user(self):
        user = make_user("pdf@example.com", self.company_a, perms=PERMS)
        Garment.objects.create(company=self.company_a, name="g", style_no="g", price=1)
        r = self.login(user).get(reverse("core:resource_export", args=["garments", "pdf"]))
        self.assertEqual(r.status_code, 200)
        self.assertIn("Generated By: pdf@example.com", pdf_text(r.content))


