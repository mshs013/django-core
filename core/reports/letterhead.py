"""PDF letterhead: the header and footer drawn on every page of every PDF core produces (list exports, report exports, custom
reports). The body of a PDF is never touched here.

Two layers, each replaceable on its own:

* :class:`Letterhead` -- the *data* (company name, address lines, e-mail, phone, website, logo, product brand). By default the
  **active company** supplies them (Companies page); a blank field falls back to ``CORE_PDF_LETTERHEAD`` (a dict that overrides
  :data:`DEFAULT_LETTERHEAD` key by key), then to empty. ``DEFAULT_LETTERHEAD`` holds no company details on purpose: a reused
  ``core`` never prints somebody else's name. ``"from_company": False`` prints only the setting's details. Nothing is cached:
  every PDF reads the company afresh, so a company switch shows at once.
* :class:`LetterheadTemplate` -- the *drawing*: ``draw_header`` / ``draw_footer`` / ``draw_signatures``. Point
  ``CORE_PDF_LETTERHEAD_CLASS`` at a subclass (dotted path) to change the layout for the whole site, or pass ``letterhead_class`` in
  a PDF's ``meta`` (custom reports take ``letterhead_class=``) to change it for one document.

The default layout follows ``work-order.pdf``: logo top left; company name, address lines, e-mail and website top right; the
document title centred above a rule. Footer: "Generated On" / "Generated By" on the left, "Page X of Y" / "This report is generated
by <brand>" on the right. Optional signature boxes (Prepared / Checked / Approved By ...) sit at the bottom of the last page.
"""
from __future__ import annotations

import io
from dataclasses import dataclass
from pathlib import Path

from django.utils import timezone
from django.utils.module_loading import import_string

from core import conf

DEFAULT_LETTERHEAD = {
    "name": "",
    "address_lines": (),
    "email": "",
    "website": "",
    "phone": "",
    "logo": "",                         # a file path, or bytes; "" = no logo
    "brand": None,                      # "This report is generated by <brand>"; None = the company's name, "" = no line
    "from_company": True,               # False: ignore the company, print only the details above
}


@dataclass(frozen=True)
class Signature:
    """One signature box: ``label`` ("Prepared By"), the signer's ``name``, ``when`` (datetime, or text, or None) and an optional
    signature ``image`` (bytes) drawn above the name."""

    label: str
    name: str = ""
    when: object = None
    image: bytes | None = None

    def image_reader(self):
        from reportlab.lib.utils import ImageReader

        try:
            return ImageReader(io.BytesIO(bytes(self.image))) if self.image else None
        except Exception:  # noqa: BLE001 - a broken signature image must never break a PDF
            return None


@dataclass(frozen=True)
class Letterhead:
    name: str = ""
    address_lines: tuple[str, ...] = ()
    email: str = ""
    website: str = ""
    phone: str = ""
    logo: object = None                 # path (str/Path) or bytes
    brand: str = ""

    def logo_reader(self):
        """A reportlab ImageReader for the logo, or None when there is none / it cannot be read."""
        from reportlab.lib.utils import ImageReader

        try:
            if isinstance(self.logo, (bytes, bytearray)) and self.logo:
                return ImageReader(io.BytesIO(bytes(self.logo)))
            if self.logo and Path(str(self.logo)).is_file():
                return ImageReader(str(self.logo))
        except Exception:  # noqa: BLE001 - a broken logo must never break a PDF
            return None
        return None


def _settings() -> dict:
    return {**DEFAULT_LETTERHEAD, **(conf.get("CORE_PDF_LETTERHEAD") or {})}


def _company_logo(company) -> bytes | None:
    if not getattr(company, "logo", None):
        return None
    try:
        with company.logo.open("rb") as handle:
            return handle.read(3_000_000)
    except Exception:  # noqa: BLE001
        return None


def _company(company_id):
    """The alive company ``company_id``, or None (no id, unknown, soft-deleted, or the table cannot be read)."""
    if not company_id:
        return None
    from core.models import Company

    try:
        return Company.objects.filter(pk=company_id).first()
    except (TypeError, ValueError):
        return None


def letterhead_for(company_id=None) -> Letterhead:
    """The letterhead for a document printed in company ``company_id`` (the active company). Each field: the company's value, else
    ``CORE_PDF_LETTERHEAD``'s, else empty. A missing or deleted company prints the setting's details only."""
    data = _settings()
    company = _company(company_id) if data.get("from_company") else None
    if company is not None:
        lines = tuple(a.strip() for a in (company.address, company.factory_address) if a and a.strip())
        name, email = company.name or "", company.email or ""
        website, phone, logo = company.website or "", company.phone or "", _company_logo(company)
    else:
        lines, name, email, website, phone, logo = (), "", "", "", "", None
    name = name or data.get("name") or ""
    brand = data.get("brand")
    return Letterhead(name=name, address_lines=lines or tuple(a for a in (data.get("address_lines") or ()) if a),
                      email=email or data.get("email") or "", website=website or data.get("website") or "",
                      phone=phone or data.get("phone") or "", logo=logo or data.get("logo") or None,
                      brand=name if brand is None else str(brand))


def user_display_name(user) -> str:
    if user is None or not getattr(user, "is_authenticated", False):
        return ""
    get_full = getattr(user, "get_full_name", None)
    return getattr(user, "full_name", "") or (get_full() if callable(get_full) else "") or getattr(user, "email", "") or str(user)


def format_when(value, pattern: str | None = None) -> str:
    """Site format (CORE_DATETIME_FORMAT / CORE_DATE_FORMAT) unless ``pattern`` is given: Django date syntax, or a legacy
    ``strftime`` pattern (contains ``%``)."""
    if value is None or value == "":
        return ""
    if pattern and "%" in pattern and hasattr(value, "strftime"):
        if hasattr(value, "tzinfo") and timezone.is_aware(value):
            value = timezone.localtime(value)
        return value.strftime(pattern)
    from core.formatting import format_value

    return format_value(value, pattern)


# ------------------------------------------------------------------------------------------------------------------- drawing
class LetterheadTemplate:
    """Draws the header, footer and signature boxes. Subclass it and override any ``draw_*`` method or the layout attributes;
    every size is in points (1/72 inch). ``meta`` is the PDF's meta dict (``title``, ``generated_by``, ``generated_at`` ...)."""

    margin_x = 24
    header_height = 80                   # space reserved at the top of every page (the body starts below it)
    footer_height = 40                   # space reserved at the bottom of every page
    signature_height = 78                # height of the signature row (last page only, above the footer)
    font, font_bold, font_italic = "Helvetica", "Helvetica-Bold", "Helvetica-Oblique"
    text_color = "#111111"
    icon_color = "#111111"
    generated_on_format = None           # None = site CORE_DATETIME_FORMAT; or a Django date pattern, e.g. "d/m/Y H:i"
    signature_date_format = None

    def __init__(self, letterhead: Letterhead, meta: dict):
        self.letterhead = letterhead
        self.meta = meta

    # -- page geometry used by the document template
    @property
    def top_margin(self) -> float:
        return self.header_height + 8

    @property
    def bottom_margin(self) -> float:
        return self.footer_height + 8

    @property
    def title(self) -> str:
        return str(self.meta.get("title") or "")

    # -- hooks called by core.reports.resources.pdf
    def on_page(self, canvas, doc) -> None:
        canvas.saveState()
        self.draw_header(canvas, doc)
        canvas.restoreState()

    def on_page_end(self, canvas, page: int, total: int) -> None:
        canvas.saveState()
        self.draw_footer(canvas, page, total)
        canvas.restoreState()

    # -- header
    def draw_header(self, canvas, doc) -> None:
        from reportlab.lib.colors import HexColor

        width, height = canvas._pagesize
        top = height - 10
        lh = self.letterhead
        logo = lh.logo_reader()
        if logo is not None:
            iw, ih = logo.getSize()
            box_w, box_h = 104, 58
            scale = min(box_w / float(iw or 1), box_h / float(ih or 1))
            canvas.drawImage(logo, self.margin_x + 2, top - ih * scale, iw * scale, ih * scale, mask="auto")
        right = width - self.margin_x
        canvas.setFillColor(HexColor(self.text_color))
        y = top - 18
        if lh.name:
            canvas.setFont(self.font, 15)
            canvas.drawRightString(right, y, lh.name)
        y -= 12
        canvas.setFont(self.font, 8)
        for line in lh.address_lines:
            self._icon_line(canvas, right, y, line, self.font, "pin")
            y -= 9.5
        if lh.phone:
            self._icon_line(canvas, right, y, lh.phone, self.font, "phone")
            y -= 9.5
        contacts = [(t, k) for t, k in ((lh.email, "mail"), (lh.website, "globe")) if t]
        if contacts:
            self._contacts_line(canvas, right, y, contacts)
        rule_y = height - self.header_height
        if self.title:
            canvas.setFont(self.font, 11.5)
            canvas.drawCentredString(width / 2, rule_y + 6, self.title[:150])
        canvas.setLineWidth(0.8)
        canvas.line(self.margin_x, rule_y, width - self.margin_x, rule_y)

    def _icon_line(self, canvas, right: float, y: float, text: str, font: str, icon: str, size: float = 8) -> None:
        canvas.setFont(font, size)
        text_w = canvas.stringWidth(text, font, size)
        canvas.drawRightString(right, y, text)
        self.draw_icon(canvas, icon, right - text_w - 7, y, size)

    def _contacts_line(self, canvas, right: float, y: float, contacts) -> None:
        """``e-mail; website`` with an icon in front of each, right aligned, in italics."""
        size, font = 8, self.font_italic
        parts = []
        for index, (text, icon) in enumerate(contacts):
            label = text + (";" if index < len(contacts) - 1 else "")
            parts.append((label, icon, canvas.stringWidth(label, font, size)))
        total = sum(w + 9 for _l, _i, w in parts) + 3 * (len(parts) - 1)
        x = right - total
        canvas.setFont(font, size)
        for label, icon, w in parts:
            self.draw_icon(canvas, icon, x, y, size)
            canvas.drawString(x + 9, y, label)
            x += w + 9 + 3

    def draw_icon(self, canvas, kind: str, x: float, y: float, size: float = 8) -> None:
        """Small vector icons (map pin, envelope, globe, phone) drawn at ``x`` (left edge), text baseline ``y``."""
        from reportlab.lib.colors import HexColor, white

        canvas.saveState()
        canvas.setFillColor(HexColor(self.icon_color))
        canvas.setStrokeColor(HexColor(self.icon_color))
        s = size / 8.0
        if kind == "pin":
            cx, cy, r = x + 2.6 * s, y + 4.6 * s, 2.3 * s
            path = canvas.beginPath()
            path.moveTo(cx - r * 0.92, cy - r * 0.4)
            path.lineTo(cx, y - 0.6 * s)
            path.lineTo(cx + r * 0.92, cy - r * 0.4)
            path.close()
            canvas.drawPath(path, stroke=0, fill=1)
            canvas.circle(cx, cy, r, stroke=0, fill=1)
            canvas.setFillColor(white)
            canvas.circle(cx, cy, r * 0.42, stroke=0, fill=1)
        elif kind == "mail":
            w, h = 6.6 * s, 4.6 * s
            canvas.rect(x, y, w, h, stroke=0, fill=1)
            canvas.setStrokeColor(white)
            canvas.setLineWidth(0.6 * s)
            canvas.lines([(x + 0.3 * s, y + h - 0.3 * s, x + w / 2, y + h / 2 - 0.2 * s), (x + w / 2, y + h / 2 - 0.2 * s, x + w - 0.3 * s, y + h - 0.3 * s)])
        elif kind == "globe":
            cx, cy, r = x + 3.1 * s, y + 2.6 * s, 3.1 * s
            canvas.circle(cx, cy, r, stroke=0, fill=1)
            canvas.setStrokeColor(white)
            canvas.setLineWidth(0.45 * s)
            canvas.ellipse(cx - r * 0.42, cy - r * 0.95, cx + r * 0.42, cy + r * 0.95, stroke=1, fill=0)
            canvas.line(cx - r * 0.95, cy, cx + r * 0.95, cy)
        elif kind == "phone":
            canvas.roundRect(x + 1 * s, y - 0.4 * s, 4 * s, 6.6 * s, 0.8 * s, stroke=0, fill=1)
            canvas.setFillColor(white)
            canvas.rect(x + 1.7 * s, y + 1.0 * s, 2.6 * s, 4.2 * s, stroke=0, fill=1)
        canvas.restoreState()

    # -- footer
    def draw_footer(self, canvas, page: int, total: int) -> None:
        from reportlab.lib.colors import HexColor

        width, _height = canvas._pagesize
        left, right = self.margin_x + 5, width - self.margin_x - 5
        y = 26
        canvas.setFillColor(HexColor(self.text_color))
        when = format_when(self.meta.get("generated_at"), self.generated_on_format)
        canvas.setFont(self.font, 8)
        if when:
            canvas.drawString(left, y, f"Generated On {when}")
        canvas.drawRightString(right, y, f"Page {page} of {total}")
        canvas.setFont(self.font_italic, 7)
        if self.meta.get("generated_by"):
            canvas.drawString(left, y - 9, f"Generated By: {self.meta['generated_by']}")
        if self.letterhead.brand:
            canvas.drawRightString(right, y - 9, f"This report is generated by {self.letterhead.brand}")

    # -- signatures (a flowable anchored to the bottom of the last page; see SignatureBlock)
    def draw_signatures(self, canvas, signatures, x: float, y: float, width: float) -> None:
        """Draw ``signatures`` in equal columns. (x, y) is the bottom-left corner of the signature row."""
        from reportlab.lib.colors import HexColor

        if not signatures:
            return
        canvas.setFillColor(HexColor(self.text_color))
        col = width / len(signatures)
        for index, sig in enumerate(signatures):
            cx = x + col * index + col / 2
            canvas.setFont(self.font_bold, 8)
            canvas.drawCentredString(cx, y + 66, sig.label)
            image = sig.image_reader()
            if image is not None:                    # the signer's signature, fitted into a box above the name
                iw, ih = image.getSize()
                scale = min(min(col - 16, 110) / float(iw or 1), 30 / float(ih or 1))
                canvas.drawImage(image, cx - iw * scale / 2, y + 30, iw * scale, ih * scale, mask="auto")
            canvas.setFont(self.font, 8)
            if sig.name:
                canvas.drawCentredString(cx, y + 20, sig.name[:60])
            when = format_when(sig.when, self.signature_date_format)
            if when:
                canvas.setFont(self.font_italic, 7)
                canvas.drawCentredString(cx, y + 10, when)


def template_class(meta: dict):
    """The LetterheadTemplate class for a document: ``meta["letterhead_class"]`` (class or dotted path), else the site setting."""
    choice = meta.get("letterhead_class") or conf.get("CORE_PDF_LETTERHEAD_CLASS")
    if not choice:
        return LetterheadTemplate
    return import_string(choice) if isinstance(choice, str) else choice


def build_template(meta: dict) -> LetterheadTemplate:
    letterhead = meta.get("letterhead") or letterhead_for(meta.get("company_id"))
    return template_class(meta)(letterhead, meta)
